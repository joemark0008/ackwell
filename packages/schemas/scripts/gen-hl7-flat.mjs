#!/usr/bin/env node
/**
 * Generates the typed flat HL7 definitions in src/hl7-flat/generated/ from hl7-dictionary (MIT).
 *
 *   npm run gen:hl7-flat -w @ackwell/schemas
 *
 * Per version it writes one file with:
 *   - one interface per composite datatype, keyed by component position relative to the field
 *     ('1', '1_2', ...), so a field type is `Prefixed<'pid_5', DT_XPN>` → `pid_5_1_1`, `pid_5_2`, ...
 *   - one interface per segment (`PID`, `OBX`, ...) carrying `segment: 'PID'` as the discriminant
 *   - `MSH` (top-level keys of the message, with `msh_12` as the version literal) and `Message`
 *   - `spec`: the compact runtime description used by toFlat / fromFlat / validateFlat
 */
import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const dict = require('hl7-dictionary');
const dictVersion = require('hl7-dictionary/package.json').version;

const VERSIONS = ['2.3', '2.5.1', '2.7'];
const OUT_DIR = join(dirname(fileURLToPath(import.meta.url)), '../src/hl7-flat/generated');

/**
 * Corrections to the dictionary. OBX-5 is "varies" (its type is named by OBX-2) and repeating in every
 * version; hl7-dictionary lists it as a single ST in 2.7.
 */
const FIELD_OVERRIDES = {
  'OBX-5': { datatype: 'VARIES', rep: 0 },
};

const clean = (s) => String(s ?? '').replace(/\s+/g, ' ').replace(/\*\//g, '*\\/').trim();
const isRepeating = (rep) => rep !== 1;

function generate(version) {
  const { fields: datatypes, segments } = dict.definitions[version];
  const isComposite = (dt) => Array.isArray(datatypes[dt]?.subfields) && datatypes[dt].subfields.length > 0;
  const id = version.replace(/\./g, '_');
  const out = [];
  const w = (s = '') => out.push(s);

  w(`// AUTO-GENERATED by scripts/gen-hl7-flat.mjs from hl7-dictionary@${dictVersion} (MIT). Do not edit.`);
  w(`/* eslint-disable */`);
  w(`import type { Hl7FlatSpec, Hl7FlatZSegment, Prefixed } from '../types';`);
  w();
  w(`export const VERSION = '${version}' as const;`);
  w();

  // ---- Datatypes actually used by segments (plus the composites they reference) -------------------
  const used = new Set();
  const visit = (dt) => {
    if (used.has(dt) || !isComposite(dt)) return;
    used.add(dt);
    for (const sf of datatypes[dt].subfields) visit(sf.datatype);
  };
  const segIds = Object.keys(segments).filter((s) => /^[A-Z][A-Z0-9]{2}$/.test(s)).sort();
  const fieldDef = (seg, i, f) => ({ ...f, ...(FIELD_OVERRIDES[`${seg}-${i + 1}`] ?? {}) });
  for (const seg of segIds) segments[seg].fields.forEach((f, i) => visit(fieldDef(seg, i, f).datatype));

  const composites = {};
  for (const dt of [...used].sort()) {
    const subs = datatypes[dt].subfields;
    composites[dt] = subs.map((s) => s.datatype);
    w(`/** ${dt}: ${clean(datatypes[dt].desc)} */`);
    w(`export interface DT_${dt} {`);
    subs.forEach((s, j) => {
      const c = j + 1;
      if (isComposite(s.datatype)) {
        datatypes[s.datatype].subfields.forEach((ss, k) => {
          w(`  /** ${dt}.${c}.${k + 1} ${clean(s.desc)} / ${clean(ss.desc)} (${ss.datatype}) */`);
          w(`  '${c}_${k + 1}'?: string;`);
        });
      } else {
        w(`  /** ${dt}.${c} ${clean(s.desc)} (${s.datatype}) */`);
        w(`  '${c}'?: string;`);
      }
    });
    w(`}`);
    w();
  }

  // ---- Segments ----------------------------------------------------------------------------------
  const specSegments = {};
  const emitSegment = (seg, isMsh) => {
    const def = segments[seg];
    const lower = seg.toLowerCase();
    const ext = [];
    const props = [];
    const spec = [];
    def.fields.forEach((raw, i) => {
      const f = fieldDef(seg, i, raw);
      const n = i + 1;
      const rep = isRepeating(f.rep);
      spec.push(f.datatype + (rep ? '*' : ''));
      if (isMsh && n <= 2) return; // MSH-1 / MSH-2 come from `delimiters`
      const key = `${lower}_${n}`;
      const doc = `/** ${seg}-${n} ${clean(f.desc)} (${f.datatype}${rep ? ', repeating' : ''}) */`;
      const comp = isComposite(f.datatype);
      if (isMsh && n === 12) {
        // The version is always `msh_12` (VID.1 when MSH-12 is a composite), so it can discriminate.
        props.push(`  /** MSH-12 Version ID: the discriminant of the message type */`, `  msh_12: '${version}';`);
        if (comp) ext.push(`Omit<Prefixed<'msh_12', DT_${f.datatype}>, 'msh_12_1'>`);
        return;
      }
      if (!comp) props.push(`  ${doc}`, `  ${key}?: ${rep ? 'string[]' : 'string'};`);
      else if (rep) props.push(`  ${doc}`, `  ${key}?: Prefixed<'${key}', DT_${f.datatype}>[];`);
      else ext.push(`Prefixed<'${key}', DT_${f.datatype}>`);
    });
    specSegments[seg] = spec;
    w(`/** ${seg}: ${clean(def.desc)} */`);
    w(`export interface ${seg}${ext.length ? ' extends\n    ' + ext.join(',\n    ') : ''} {`);
    if (!isMsh) w(`  segment: '${seg}';`);
    for (const p of props) w(p);
    w(`  /** Fields that do not fit the ${version} definition, as raw HL7 text keyed \`${lower}_<n>\`. */`);
    w(`  _extra?: Record<string, string>;`);
    w(`}`);
    w();
  };
  emitSegment('MSH', true);
  const bodySegs = segIds.filter((s) => s !== 'MSH');
  for (const seg of bodySegs) emitSegment(seg, false);

  w(`/** Any segment after MSH: a ${version} segment, or a Z-segment kept positional. */`);
  w(`export type Segment =`);
  for (const seg of bodySegs) w(`  | ${seg}`);
  w(`  | Hl7FlatZSegment;`);
  w();
  w(`/** A whole HL7 ${version} message: MSH keys at the top level, the other segments in order. */`);
  w(`export interface Message extends MSH {`);
  w(`  delimiters?: { field: string; component: string; repeat: string; escape: string; subcomponent: string };`);
  w(`  segments?: Segment[];`);
  w(`}`);
  w();
  w(`export const spec: Hl7FlatSpec = ${JSON.stringify({ version, composites, segments: specSegments })};`);

  const unknownTypes = new Set();
  for (const seg of segIds)
    segments[seg].fields.forEach((f, i) => {
      const dt = fieldDef(seg, i, f).datatype;
      if (!datatypes[dt]) unknownTypes.add(dt);
    });

  const file = join(OUT_DIR, `v${id}.ts`);
  writeFileSync(file, out.join('\n') + '\n');
  console.log(
    `${version}: ${segIds.length} segments, ${used.size} composite datatypes → ${file}` +
      (unknownTypes.size ? `\n  primitive (not in dictionary): ${[...unknownTypes].sort().join(' ')}` : ''),
  );
}

mkdirSync(OUT_DIR, { recursive: true });
for (const v of VERSIONS) generate(v);
